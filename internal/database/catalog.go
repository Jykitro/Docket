// ErrPreviousLayout is returned before changing application tables.
var ErrPreviousLayout = errors.New("this installation uses a previous database layout; select a new empty database for Plandillo")

const catalogDDL = `
CREATE TABLE plandillo_installation(version INTEGER PRIMARY KEY CHECK(version=2), last_backup_at TEXT);
INSERT INTO plandillo_installation(version) VALUES(2);
CREATE TABLE users(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 username TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL,
 photo BLOB,
 is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
 role TEXT NOT NULL CHECK(role IN ('admin','user')),
 is_admin INTEGER GENERATED ALWAYS AS (CASE WHEN role='admin' THEN 1 ELSE 0 END) STORED,
 created_at INTEGER NOT NULL,
 updated_at INTEGER NOT NULL
);
CREATE TABLE password_credentials(user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,password_hash TEXT NOT NULL);
CREATE TABLE workspaces(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 owner_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL,
 slug TEXT NOT NULL DEFAULT '',
 icon TEXT NOT NULL DEFAULT 'board',
 icon_png BLOB,
 generation TEXT NOT NULL UNIQUE,
 mcp_token TEXT,
 token_digest TEXT UNIQUE,
 mcp_access_mode TEXT NOT NULL DEFAULT 'rw' CHECK(mcp_access_mode IN ('rw','ro')),
 mcp_disabled_tools TEXT NOT NULL DEFAULT '["delete_tasks"]',
 archived_at INTEGER,
 created_at INTEGER NOT NULL,
 updated_at INTEGER NOT NULL
);
CREATE INDEX workspaces_owner ON workspaces(owner_user_id,archived_at,id);
CREATE UNIQUE INDEX workspaces_slug ON workspaces(owner_user_id,slug);
`

// Codes, access tokens and refresh tokens have independent lifetimes. Only their digests
// reach storage. A used refresh token identifies its family until the grant expires.
const oauthSchema = `
CREATE TABLE IF NOT EXISTS oauth_grants (
 id TEXT PRIMARY KEY, workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 credential_epoch TEXT NOT NULL, client_id TEXT NOT NULL, client_name TEXT NOT NULL, resource TEXT NOT NULL,
 redirect_uri TEXT NOT NULL, scope TEXT NOT NULL, challenge TEXT NOT NULL,
 code_hash TEXT UNIQUE, access_hash TEXT UNIQUE, refresh_hash TEXT UNIQUE,
 access_until INTEGER NOT NULL DEFAULT 0, expires INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS oauth_grants_workspace ON oauth_grants(workspace_id);
CREATE INDEX IF NOT EXISTS oauth_grants_expiry ON oauth_grants(expires);
CREATE TABLE IF NOT EXISTS oauth_used_refresh (
 token_hash TEXT PRIMARY KEY, grant_id TEXT NOT NULL REFERENCES oauth_grants(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS oauth_used_family ON oauth_used_refresh(grant_id);
`

func (d *DB) EnsureCatalog(tx *Tx) error {
	var versioned, occupied bool
	q := "SELECT EXISTS(SELECT 1 FROM sqlite_master WHERE name='plandillo_installation'),EXISTS(SELECT 1 FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%')"
	if d.Postgres {
		q = "SELECT to_regclass('plandillo_installation') IS NOT NULL, EXISTS(SELECT 1 FROM pg_catalog.pg_tables WHERE schemaname=current_schema())"
	}
	if err := tx.QueryRow(q).Scan(&versioned, &occupied); err != nil {
		return err
	}
	if versioned {
		var version int
		if err := tx.QueryRow("SELECT version FROM plandillo_installation").Scan(&version); err != nil {
			return err
		}
		if version != 2 && (d.Postgres || version != 3) {
			return ErrPreviousLayout
		}
		if err := ensureSpaceSlugs(tx); err != nil {
			return err
		}
		return d.ensureOAuthCatalog(tx)
	}
	if !occupied && d.Postgres && strings.HasSuffix(d.schema, "_auth") {
		if err := tx.QueryRow("SELECT EXISTS(SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname ~ '^(docket|plandillo)_user_[1-9][0-9]*$')").Scan(&occupied); err != nil {
			return err
		}
	}
	if occupied {
		return ErrPreviousLayout
	}
	ddl := catalogDDL
	if d.Postgres {
		ddl = strings.ReplaceAll(ddl, "INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
		ddl = strings.ReplaceAll(ddl, "INTEGER", "BIGINT")
		ddl = strings.ReplaceAll(ddl, "BLOB", "BYTEA")
	}
	if _, err := tx.Exec(ddl); err != nil {
		return err
	}
	return d.ensureOAuthCatalog(tx)
}

// ensureSpaceSlugs gives workspaces made before addresses used slugs (/w/<id>/) their slug.
func ensureSpaceSlugs(tx *Tx) error {
	q := "SELECT EXISTS(SELECT 1 FROM pragma_table_info('workspaces') WHERE name='slug')"
	if tx.Postgres() {
		q = "SELECT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='workspaces' AND column_name='slug')"
	}
	var done bool
	if err := tx.QueryRow(q).Scan(&done); err != nil || done {
		return err
	}
	if _, err := tx.Exec("ALTER TABLE workspaces ADD COLUMN slug TEXT NOT NULL DEFAULT ''"); err != nil {
		return err
	}
	rows, err := tx.Query("SELECT id,owner_user_id,name FROM workspaces ORDER BY id")
	if err != nil {
		return err
	}
	type space struct {
		id, owner int64
		name      string
	}
	var all []space
	for rows.Next() {
		var v space
		if err = rows.Scan(&v.id, &v.owner, &v.name); err != nil {
			rows.Close()
			return err
		}
		all = append(all, v)
	}
	rows.Close()
	if err = rows.Err(); err != nil {
		return err
	}
	for _, v := range all {
		s, err := tx.SpaceSlug(v.owner, v.name)
		if err != nil {
			return err
		}
		if _, err = tx.Exec("UPDATE workspaces SET slug=? WHERE id=?", s, v.id); err != nil {
			return err
		}
	}
	_, err = tx.Exec("CREATE UNIQUE INDEX workspaces_slug ON workspaces(owner_user_id,slug)")
	return err
}

// reservedSlugs are first segments of addresses outside a workspace (server routes, sign-in pages, old /w/<id>/
// links) and the app's own pages, which an address without a workspace is redirected into.
var reservedSlugs = map[string]bool{"api": true, "assets": true, "healthz": true, "mcp": true, "oauth": true, "register": true,
	"recover": true, "invite": true, "w": true, "p": true, "t": true, "attention": true, "integrations": true, "trash": true, "settings": true}

// SpaceSlug is a free address word for a new workspace of owner: its name in a-z0-9 words, then -2, -3… on a clash.
func (t *Tx) SpaceSlug(owner int64, name string) (string, error) {
	base := slug.ASCII(name)
	if base == "" || reservedSlugs[base] || strings.Trim(base, "0123456789") == "" { // all digits would read as an ID
		base = strings.TrimSuffix("space-"+base, "-")
	}
	s := base
	for i := 2; ; i++ {
		var taken bool
		if err := t.QueryRow("SELECT EXISTS(SELECT 1 FROM workspaces WHERE owner_user_id=? AND slug=?)", owner, s).Scan(&taken); err != nil || !taken {
			return s, err
		}
		s = base + "-" + strconv.Itoa(i)
	}
}

func (d *DB) ensureOAuthCatalog(tx *Tx) error {
	ddl := oauthSchema
	if d.Postgres {
		ddl = strings.ReplaceAll(ddl, "INTEGER", "BIGINT")
	}
	_, err := tx.Exec(ddl)
	return err
}

// CheckSQLiteLayout examines an existing file before the writable connection changes
// its journal mode or file permissions. A missing or empty file is a fresh install.
func CheckSQLiteLayout(path string) error {
	info, err := os.Stat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if info.Size() == 0 {
		return nil
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		return err
	}
	uri := url.URL{Scheme: "file", Path: abs, RawQuery: "mode=ro"}
	db, err := sql.Open("sqlite", uri.String())
	if err != nil {
		return err
	}
	defer db.Close()
	var valid, occupied bool
	err = db.QueryRowContext(context.Background(), "SELECT EXISTS(SELECT 1 FROM sqlite_master WHERE name='plandillo_installation'),EXISTS(SELECT 1 FROM sqlite_master WHERE name NOT LIKE 'sqlite_%')").Scan(&valid, &occupied)
	if err == nil && occupied && !valid {
		return ErrPreviousLayout
	}
	return err
}
