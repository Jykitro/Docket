// Uses the built binary with disposable storage and a real isolated Code Mode process.
const { test, expect } = require('playwright/test')
const { spawn } = require('node:child_process')
const { once } = require('node:events')
const { createServer } = require('node:net')
const { mkdtemp, readFile, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const path = require('node:path')

test.use({ locale: 'en-GB', viewport: { width: 1280, height: 900 } })
test('signup, private data, recovery and worker availability', async ({ page, browser }) => {
  const dir = await mkdtemp(path.join(tmpdir(), 'dck-'))
  const socket = createServer()
  socket.listen(0,'127.0.0.1')
  await once(socket,'listening')
  const addr = '127.0.0.1:' + socket.address().port
  await new Promise(resolve => socket.close(resolve))
  const url = 'http://' + addr
  const bin = process.env.DOCKET_TEST_BINARY || path.resolve(__dirname,'../../bin/docket')
  const env = { PATH: process.env.PATH, DOCKET_CODE_SOCKET: path.join(dir,'code.sock'), DOCKET_MODE: 'selfhost',
    DOCKET_ADDR: addr, DOCKET_DB: path.join(dir,'planner.db'), DOCKET_BACKUP_DIR: path.join(dir,'backups') }
  const worker = spawn(bin,['code-runner'],{env,stdio:'ignore'})
  const stoppedWorker = once(worker,'exit')
  const app = spawn(bin,[],{env,stdio:['ignore','ignore','pipe']})
  const stoppedApp = once(app,'exit')
  const ownerContext = await browser.newContext({locale:'en-GB', viewport:{width:390,height:844}})
  try {
    const setupFile = path.join(dir, 'setup-code')
    await expect.poll(() => readFile(setupFile, 'utf8').then(Boolean, () => false)).toBe(true)
    const setup = (await readFile(setupFile, 'utf8')).trim()
    const post = (client,route,data) => client.post(url+route,{data,failOnStatusCode:true})
    const admin = page.request
    await post(admin,'/api/auth/setup',{code:setup,username:'operator',password:'test-password-123'})
    await post(admin,'/api/projects',{name:'Operator private',key:'OWN'})
    await page.goto(url)
    await page.getByRole('button',{name:'Settings',exact:true}).click()
    const selector = page.getByRole('combobox',{name:'Registration',exact:true})
    await expect(selector).toHaveValue('invite')
    await selector.selectOption('open')
    await expect.poll(async()=> (await (await admin.get(url+'/api/auth/registration')).json()).mode).toBe('open')

    const owner = await ownerContext.newPage()
    await owner.goto(url)
    await owner.getByRole('link',{name:'Create account'}).click()
    await owner.locator('input[autocomplete=username]').fill('pilot')
    await owner.locator('input[autocomplete=new-password]').fill('owner-password-123')
    await owner.getByRole('button',{name:'Create account'}).click()
    await expect(owner.getByRole('heading',{name:'Save your recovery code'})).toBeVisible()
    const code = await owner.locator('code').textContent()
    await owner.getByRole('button',{name:'I saved the code'}).click()
    const api = owner.request
    const project = await (await post(api,'/api/projects',{name:'Pilot private',key:'OWN'})).json()
    const wiki = await (await post(api,'/api/projects/'+project.id+'/pages',{title:'Report',body_html:'<button>Local report</button>'})).json()
    await owner.goto(url+'/p/'+project.slug+'/wiki/'+wiki.id)
    await expect(owner.frameLocator('iframe').first().frameLocator('iframe').getByRole('button',{name:'Local report'})).toBeVisible()
    const frames=owner.frames()
    const content=frames.find(frame=>frame.parentFrame()?.parentFrame())
    expect(await content.evaluate(()=>self.origin)).toBe('null')
    expect(await owner.locator('iframe').first().getAttribute('sandbox')).toBe('allow-scripts')
    expect(await owner.getByText('Operator private').count()).toBe(0)
    expect(await owner.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)

    const token = async client => (await (await client.get(url+'/api/mcp/token',{failOnStatusCode:true})).json()).token
    async function call(client,bearer,endpoint,name,args){
      const r=await client.post(url+endpoint,{headers:{Authorization:'Bearer '+bearer,Accept:'application/json, text/event-stream'},data:{jsonrpc:'2.0',id:1,method:'tools/call',params:{name,arguments:args}},failOnStatusCode:true})
      return (await r.json()).result
    }
    const ownerToken = await token(api)
    const adminToken = await token(admin)
    for (const [client,bearer,mine,other] of [[api,ownerToken,'Pilot private','Operator private'],[admin,adminToken,'Operator private','Pilot private']]){
      const result=await call(client,bearer,'/mcp/code','code',{code:'return await codemode.list_projects({})'})
      expect(result.isError).toBeFalsy()
      expect(result.content[0].text).toContain(mine)
      expect(result.content[0].text).not.toContain(other)
    }
    worker.kill()
    await stoppedWorker
    expect((await call(api,ownerToken,'/mcp/code','code',{code:'return 1'})).isError).toBe(true)
    expect((await call(admin,adminToken,'/mcp','list_projects',{})).content[0].text).toContain('Operator private')
    await post(admin,'/api/tasks',{project:'OWN',title:'While worker is offline'})

    await post(api,'/api/auth/logout',{})
    await owner.goto(url+'/recover')
    await owner.locator('input[autocomplete=username]').fill('pilot')
    await owner.getByLabel('Recovery code',{exact:true}).fill(code)
    await owner.locator('input[autocomplete=new-password]').fill('changed-password-123')
    await owner.getByRole('button',{name:'Recover account'}).click()
    await expect(owner.getByRole('heading',{name:'Save your recovery code'})).toBeVisible()
    await owner.getByRole('button',{name:'I saved the code'}).click()
    await owner.locator('input[autocomplete=username]').fill('pilot')
    await owner.locator('input[autocomplete=current-password]').fill('changed-password-123')
    await owner.getByRole('button',{name:'Sign in'}).click()
    await expect.poll(async()=> (await api.get(url+'/api/projects')).status()).toBe(200)
    await owner.setViewportSize({width:1280,height:900})
    await expect(owner.getByRole('link',{name:'Pilot private'}).first()).toBeVisible()
    await owner.getByRole('button',{name:'Settings',exact:true}).click()
    await owner.getByRole('button',{name:'Sign out',exact:true}).click()
    await owner.locator('input[autocomplete=username]').fill('operator')
    await owner.locator('input[autocomplete=current-password]').fill('test-password-123')
    await owner.getByRole('button',{name:'Sign in'}).click()
    await expect(owner.getByRole('link',{name:'Operator private'}).first()).toBeVisible()
    await expect(owner.getByText('Pilot private',{exact:true})).toHaveCount(0)

    // A sibling using the same cookies changes account directly, so no storage event announces it.
    const mine = await (await post(admin, '/api/tasks', { project: 'OWN', title: 'Operator report' })).json()
    const pilot = await (await post(api, '/api/auth/login', { username: 'pilot', password: 'changed-password-123' })).json()
    expect(pilot.username).toBe('pilot')
    await post(api, '/api/tasks', { project: 'OWN', title: 'Pilot task 1' })
    const theirs = await (await post(api, '/api/tasks', { project: 'OWN', title: 'Pilot report' })).json()
    expect(theirs.code).toBe(mine.code)
    await post(api, '/api/html-documents', { task: theirs.code, title: 'Pilot attachment', html: '<p>Pilot copy</p>', expected_version: 0 })
    await post(admin, '/api/html-documents', { task: mine.code, title: 'Operator attachment', html: '<p>Operator copy</p>', expected_version: 0 })
    await post(api, '/api/auth/login', { username: 'operator', password: 'test-password-123' })
    await owner.goto(url + '/t/' + mine.code)
    await owner.getByRole('article', { name: 'Operator attachment' }).locator('summary').click()
    await owner.getByRole('article', { name: 'Operator attachment' }).getByRole('button', { name: 'Edit' }).click()
    await owner.getByLabel('HTML source').fill('Private operator draft')
    const sibling = await ownerContext.newPage()
    await post(sibling.request, '/api/auth/login', { username: 'pilot', password: 'changed-password-123' })
    await owner.getByRole('button', { name: 'Publish' }).click()
    await expect(owner.getByRole('article', { name: 'Pilot attachment' })).toBeVisible()
    await expect(owner.getByLabel('HTML source')).toHaveCount(0)
    await expect(owner.getByText('Operator attachment')).toHaveCount(0)
    const pilotDetail = await (await api.get(url + '/api/tasks/' + theirs.code)).json()
    expect(pilotDetail.documents).toHaveLength(1)
    expect(pilotDetail.documents[0].version).toBe(1)

    await owner.getByRole('button', { name: 'Settings', exact: true }).click()
    await owner.getByRole('button', { name: 'New recovery code' }).click()
    await owner.getByLabel('Current password', { exact: true }).last().fill('changed-password-123')
    await owner.getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(owner.getByText('Save your recovery code')).toBeVisible()
    await post(sibling.request, '/api/auth/login', { username: 'operator', password: 'test-password-123' })
    await owner.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(owner.getByRole('article', { name: 'Operator attachment' })).toBeVisible()
    await expect(owner.getByText('Save your recovery code')).toHaveCount(0)
    await sibling.close()
  } finally {
    await ownerContext.close()
    app.kill(); worker.kill()
    await Promise.all([stoppedApp,stoppedWorker])
    await rm(dir,{recursive:true,force:true})
  }
})
